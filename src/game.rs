// sound effects, generated by tools/generate_sfx.py, named for their files
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, EnumIter, strum::IntoStaticStr)]
#[strum(serialize_all = "snake_case")]
pub enum Sfx {
    Move,
    Rotate,
    Lock,
    HardDrop,
    Hold,
    LineClear,
    #[strum(to_string = "line_clear_2")]
    LineClear2,
    #[strum(to_string = "line_clear_3")]
    LineClear3,
    Quad,
    LevelUp,
    HighScore,
    MenuMove,
    MenuSelect,
}

impl Sfx {
    fn volume(self, level: u8) -> f32 {
        match self {
            Sfx::HighScore => volume(level, HIGH_SCORE_VOL_MAX),
            _ => volume(level, SFX_VOL_MAX),
        }
    }
}

pub struct Assets {
    music: Vec<audio::Track>,
    theme: Theme, // chosen for games
    track: Theme, // playing
    music_speed: f32,
    game_over: audio::Track,
    sfx: HashMap<Sfx, audio::Track>,
    pub menu_sounds: bool, // menu move and select
    // sources paused on focus loss
    music_suspended: bool,
    game_over_suspended: bool,
}

impl Assets {
    fn new(ctx: &mut Context) -> GameResult<Self> {
        // volumes are set from the settings
        let music = Theme::VARIANTS.iter().map(|theme| {
            let path = format!("/music_{}.ogg", theme.name().to_lowercase());
            audio::Track::new(ctx, &path)
        });
        let sfx = Sfx::iter().map(|effect| {
            let path = format!("/{}.ogg", <&str>::from(effect));
            Ok((effect, audio::Track::plain(ctx, &path)?))
        });
        Ok(Assets {
            music: music.collect::<GameResult<_>>()?,
            theme: Theme::default(),
            track: TITLE_THEME,
            music_speed: 1.0,
            game_over: audio::Track::plain(ctx, "/game_over_8bit.ogg")?,
            sfx: sfx.collect::<GameResult<_>>()?,
            menu_sounds: true,
            music_suspended: false,
            game_over_suspended: false,
        })
    }

    fn play(&mut self, effect: Sfx) {
        let menu = matches!(effect, Sfx::MenuMove | Sfx::MenuSelect);
        if menu && !self.menu_sounds {
            return;
        }
        if let Some(source) = self.sfx.get_mut(&effect) {
            source.play();
        }
    }

    fn music(&self) -> &audio::Track {
        &self.music[self.track as usize]
    }

    fn music_mut(&mut self) -> &mut audio::Track {
        &mut self.music[self.track as usize]
    }

    /// switch to the chosen theme in games, the title theme elsewhere
    fn select_track(&mut self, game: bool, play: bool) {
        let track = if game { self.theme } else { TITLE_THEME };
        if track == self.track {
            return;
        }
        self.music_mut().stop();
        self.track = track;
        self.music_speed = 1.0;
        self.apply_music_speed();
        if play {
            self.music_mut().play();
        }
    }

    fn set_music_level(&mut self, level: u8) {
        for track in &mut self.music {
            track.set_volume(volume(level, MUSIC_VOL_MAX));
        }
    }

    /// pause the music for the game over jingle
    fn play_game_over(&mut self) {
        self.music().pause();
        self.game_over.play();
    }

    /// ease the music speed toward target
    fn update_music_speed(&mut self, delta_time: f64, target: f32) {
        let t = 1.0 - (-(delta_time as f32) / MUSIC_RAMP_TIME).exp();
        self.music_speed += (target - self.music_speed) * t;
        if (target - self.music_speed).abs() < 0.0005 {
            self.music_speed = target;
        }
        self.apply_music_speed();
    }

    fn apply_music_speed(&self) {
        self.music().set_tempo(self.music_speed);
    }

    /// stop the jingle and restart the music from the top
    fn end_game_over(&mut self) {
        self.game_over.stop();
        if self.music().paused() {
            self.music_speed = 1.0;
            self.apply_music_speed();
            self.music_mut().play();
        }
    }

    /// pause whatever is playing while unfocused
    fn suspend(&mut self) {
        self.music_suspended = self.music().playing();
        self.game_over_suspended = self.game_over.playing();
        self.music().pause();
        self.game_over.pause();
    }

    /// resume what suspend paused
    fn unsuspend(&mut self) {
        if std::mem::take(&mut self.music_suspended) {
            self.music().resume();
        }
        if std::mem::take(&mut self.game_over_suspended) {
            self.game_over.resume();
        }
    }

    fn set_sound_level(&mut self, level: u8) {
        for (effect, source) in &mut self.sfx {
            source.set_volume(effect.volume(level));
        }
        self.game_over.set_volume(volume(level, JINGLE_VOL_MAX));
    }
}

fn volume(level: u8, max: f32) -> f32 {
    max * level as f32 / VOLUME_LEVELS as f32
}

