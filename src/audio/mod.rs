//! music and sound effects on rodio, driven by messages and settings resources

use std::collections::HashMap;
use std::sync::Arc;

use bevy::prelude::*;
use bevy::window::WindowFocused;
use strum::{EnumIter, IntoEnumIterator};

use crate::{GameResult, Resources};

mod music;
mod sfx;
