// made by tools/make_chiptune.py
pub const MUSIC_THEMES: [(&str, &str); 6] = [
    ("Dance", "music_dance.ogg"),
    ("Bounce", "music_bounce.ogg"),
    ("Baroque", "music_baroque.ogg"),
    ("Nocturne", "music_nocturne.ogg"),
    ("Storms", "music_storms.ogg"),
    ("Shanty", "music_shanty.ogg"),
];
pub const VOLUME_LEVELS: u8 = 10; // steps on the options volume sliders
pub const DEFAULT_VOLUME_LEVEL: u8 = 5;
const MUSIC_VOL_MAX: f32 = 0.2;
const MUSIC_RAMP_TIME: f32 = 0.6; // seconds, speed change time constant
const SFX_VOL_MAX: f32 = 1.0;
const JINGLE_VOL_MAX: f32 = 0.2; // jingles are mastered louder
const HIGH_SCORE_VOL_MAX: f32 = 0.25;

// sound effects, generated by tools/generate_sfx.py
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, EnumIter)]
pub enum Sfx {
    Move,
    Rotate,
    Lock,
    HardDrop,
    Hold,
    LineClear,
    LineClear2,
    LineClear3,
    Quad,
    LevelUp,
    HighScore,
    MenuMove,
    MenuSelect,
}

impl Sfx {
    fn path(self) -> &'static str {
        match self {
            Sfx::Move => "move.ogg",
            Sfx::Rotate => "rotate.ogg",
            Sfx::Lock => "lock.ogg",
            Sfx::HardDrop => "hard_drop.ogg",
            Sfx::Hold => "hold.ogg",
            Sfx::LineClear => "line_clear.ogg",
            Sfx::LineClear2 => "line_clear_2.ogg",
            Sfx::LineClear3 => "line_clear_3.ogg",
            Sfx::Quad => "quad.ogg",
            Sfx::LevelUp => "level_up.ogg",
            Sfx::HighScore => "high_score.ogg",
            Sfx::MenuMove => "menu_move.ogg",
            Sfx::MenuSelect => "menu_select.ogg",
        }
    }

    fn volume(self, level: u8) -> f32 {
        match self {
            Sfx::HighScore => volume(level, HIGH_SCORE_VOL_MAX),
            _ => volume(level, SFX_VOL_MAX),
        }
    }
}

fn volume(level: u8, max: f32) -> f32 {
    max * level as f32 / VOLUME_LEVELS as f32
}

/// play a sound effect, a replay cuts off the last one
#[derive(Message, Debug, Clone, Copy)]
pub struct PlaySfx(pub Sfx);

/// music changes for the game over jingle
#[derive(Message, Debug, Clone, Copy, PartialEq)]
pub enum MusicCue {
    /// pause the music for the game over jingle
    GameOver,
    /// stop the jingle and restart the music from the top
    EndGameOver,
}

/// audio options, applied when changed
#[derive(Resource, Debug, Clone, PartialEq)]
pub struct AudioSettings {
    pub theme: usize,
    pub music_level: u8,
    pub sound_level: u8,
    pub play_unfocused: bool, // music keeps playing when the window loses focus
}

impl Default for AudioSettings {
    fn default() -> Self {
        AudioSettings {
            theme: 0,
            music_level: DEFAULT_VOLUME_LEVEL,
            sound_level: DEFAULT_VOLUME_LEVEL,
            play_unfocused: false,
        }
    }
}

/// music playback rate the game wants, eased toward
#[derive(Resource, Debug, Clone, Copy, PartialEq)]
pub struct MusicTempo(pub f32);

impl Default for MusicTempo {
    fn default() -> Self {
        MusicTempo(1.0)
    }
}

pub struct AudioPlugin {
    pub silent: bool, // load everything but never start the music
}

impl Plugin for AudioPlugin {
    fn build(&self, app: &mut App) {
        let silent = self.silent;
        app.add_message::<PlaySfx>()
            .add_message::<MusicCue>()
            .init_resource::<AudioSettings>()
            .init_resource::<MusicTempo>()
            .add_systems(
                PreStartup,
                move |mut commands: Commands, resources: Res<Resources>| {
                    let audio = Audio::new(&resources, silent).expect("could not load the audio");
                    commands.insert_resource(audio);
                },
            )
            .add_systems(
                Update,
                (
                    apply_settings.run_if(resource_changed::<AudioSettings>),
                    focus,
                    music_cues,
                    play_sfx,
                    keep_playing,
                )
                    .chain(),
            )
            .add_systems(FixedPostUpdate, ease_tempo);
    }
}

#[derive(Resource)]
struct Audio {
    _device: Option<rodio::MixerDeviceSink>, // output stops when dropped
    silent: bool,
    music: Vec<music::Track>,
    theme: usize,
    speed: f32,
    game_over: music::Jingle,
    sfx: HashMap<Sfx, sfx::Effect>,
    focused: bool,
    // sources paused on focus loss
    music_suspended: bool,
    game_over_suspended: bool,
}

impl Audio {
    fn new(resources: &Resources, silent: bool) -> GameResult<Self> {
        let load = |path: &str| resources.load(path).map(Arc::<[u8]>::from);
        // without an output device, play into a mixer nothing reads
        let device = if silent {
            None
        } else {
            rodio::DeviceSinkBuilder::open_default_sink()
                .inspect_err(|e| log::warn!("no audio output: {e}"))
                .ok()
        };
        let mixer = match &device {
            Some(device) => device.mixer().clone(),
            None => {
                let (mixer, _) = rodio::mixer::mixer(
                    std::num::NonZero::new(2).unwrap(),
                    std::num::NonZero::new(44_100).unwrap(),
                );
                mixer
            }
        };
        let mut music = Vec::new();
        for (_, path) in MUSIC_THEMES {
            music.push(music::Track::new(&mixer, load(path)?));
        }
        let game_over = music::Jingle::new(&mixer, load("game_over_8bit.ogg")?);
        let mut sfx = HashMap::new();
        for effect in Sfx::iter() {
            sfx.insert(effect, sfx::Effect::new(&mixer, load(effect.path())?));
        }
        Ok(Audio {
            _device: device,
            silent,
            music,
            theme: 0,
            speed: 1.0,
            game_over,
            sfx,
            focused: true,
            music_suspended: false,
            game_over_suspended: false,
        })
    }

    fn music(&self) -> &music::Track {
        &self.music[self.theme]
    }

    fn music_mut(&mut self) -> &mut music::Track {
        let theme = self.theme;
        &mut self.music[theme]
    }

    fn apply_speed(&self) {
        self.music().set_tempo(self.speed);
    }
}

fn apply_settings(settings: Res<AudioSettings>, mut audio: ResMut<Audio>) {
    let theme = settings.theme.min(audio.music.len() - 1);
    if theme != audio.theme {
        // a new theme starts from the top
        let playing = !audio.music().stopped();
        audio.music_mut().stop();
        audio.theme = theme;
        audio.apply_speed();
        if playing && !audio.silent {
            audio.music_mut().play();
        }
    }
    for track in &mut audio.music {
        track.set_volume(volume(settings.music_level, MUSIC_VOL_MAX));
    }
    for (effect, source) in &mut audio.sfx {
        source.set_volume(effect.volume(settings.sound_level));
    }
    audio
        .game_over
        .set_volume(volume(settings.sound_level, JINGLE_VOL_MAX));
}

/// music and the game over jingle stop while unfocused, unless set to keep playing
fn focus(
    mut events: MessageReader<WindowFocused>,
    settings: Res<AudioSettings>,
    mut audio: ResMut<Audio>,
) {
    for event in events.read() {
        if audio.silent || event.focused == audio.focused {
            continue;
        }
        audio.focused = event.focused;
        if event.focused {
            if std::mem::take(&mut audio.music_suspended) {
                audio.music().resume();
            }
            if std::mem::take(&mut audio.game_over_suspended) {
                audio.game_over.resume();
            }
        } else if !settings.play_unfocused {
            audio.music_suspended = audio.music().playing();
            audio.game_over_suspended = audio.game_over.playing();
            audio.music().pause();
            audio.game_over.pause();
        }
    }
}

fn music_cues(mut cues: MessageReader<MusicCue>, mut audio: ResMut<Audio>) {
    for cue in cues.read() {
        if audio.silent {
            continue;
        }
        match cue {
            MusicCue::GameOver => {
                audio.music().pause();
                audio.game_over.play();
            }
            MusicCue::EndGameOver => {
                audio.game_over.stop();
                if audio.music().paused() {
                    audio.speed = 1.0;
                    audio.apply_speed();
                    audio.music_mut().play();
                }
            }
        }
    }
}

fn play_sfx(mut sounds: MessageReader<PlaySfx>, mut audio: ResMut<Audio>) {
    for PlaySfx(effect) in sounds.read() {
        if let Some(source) = audio.sfx.get_mut(effect) {
            source.play();
        }
    }
}

/// loop the music, rodio 0.22 repeat is silent for vorbis
fn keep_playing(settings: Res<AudioSettings>, mut audio: ResMut<Audio>) {
    if !audio.silent && (audio.focused || settings.play_unfocused) && audio.music().stopped() {
        audio.music_mut().play();
    }
}

/// ease the music speed toward the tempo
fn ease_tempo(time: Res<Time>, tempo: Res<MusicTempo>, mut audio: ResMut<Audio>) {
    let t = 1.0 - (-time.delta_secs() / MUSIC_RAMP_TIME).exp();
    audio.speed += (tempo.0 - audio.speed) * t;
    if (tempo.0 - audio.speed).abs() < 0.0005 {
        audio.speed = tempo.0;
    }
    audio.apply_speed();
}
